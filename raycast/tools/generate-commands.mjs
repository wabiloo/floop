#!/usr/bin/env node
// Generates one root-level Raycast command per favourite script, so each can have its own
// alias/hotkey in Raycast. Edit favourites.json, run `npm run generate`, then rebuild.
import { readFileSync, writeFileSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadScripts, findScript } from "../../runner/index.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(root, "..");
const favourites = JSON.parse(readFileSync(join(root, "favourites.json"), "utf8"));
const scripts = loadScripts([join(repo, "Boop/Boop/scripts"), join(repo, "Scripts")]);

const pkgPath = join(root, "package.json");
const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
const slug = (f) => "script-" + f.replace(/\.js$/, "").replace(/[^A-Za-z0-9]+/g, "-").toLowerCase();

for (const f of readdirSync(join(root, "src"))) if (/^script-.*\.ts$/.test(f)) rmSync(join(root, "src", f));
const generated = [];
for (const fav of favourites) {
  const s = findScript(scripts, fav);
  if (!s) { console.error(`! no script matching "${fav}", skipped`); continue; }
  const name = slug(s.file);
  if (generated.some((c) => c.name === name)) continue;
  generated.push({
    name,
    title: `Floop: ${s.name}`,
    subtitle: "Floop",
    description: s.description || `Run ${s.name} on the selected text or clipboard.`,
    mode: "no-view",
    preferences: [{
      name: "output", type: "dropdown", title: "Output", label: "After running", required: false, default: "paste",
      data: [{ title: "Paste over selection", value: "paste" }, { title: "Copy to clipboard", value: "copy" }],
    }],
  });
  writeFileSync(join(root, "src", `${name}.ts`),
    `// Generated by tools/generate-commands.mjs. Do not edit.\nimport { runFavourite } from "./run-favourite";\n\nexport default () => runFavourite(${JSON.stringify(s.file)});\n`);
}
pkg.commands = [...pkg.commands.filter((c) => !c.name.startsWith("script-")), ...generated];
writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n");
console.log(`Generated ${generated.length} commands: ${generated.map((c) => c.title).join(", ")}`);
